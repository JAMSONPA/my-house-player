"""Teste automático do Jamson Player: usa o app como o controle remoto da TV."""
import asyncio, os, sys
from playwright.async_api import async_playwright

BASE = os.environ.get('BASEURL', 'http://localhost:8099/app/index.html') + os.environ.get('Q', '')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'capturas') + os.environ.get('SUF', '')
os.makedirs(OUT, exist_ok=True)
erros, falhas, oks = [], [], []

def ok(cond, msg):
    (oks if cond else falhas).append(msg)
    print(('  OK   ' if cond else '  FALHA') + ' ' + msg)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome',
                                    args=['--no-sandbox', '--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(viewport={'width': 1920, 'height': 1080})
        pg = await ctx.new_page()
        pg.on('pageerror', lambda e: erros.append('JS: ' + str(e)))
        pg.on('console', lambda m: erros.append('console: ' + m.text) if m.type == 'error' and 'logo-quebrado' not in m.text and '404' not in m.text else None)

        async def tecla(k, n=1, espera=250):
            for _ in range(n):
                await pg.keyboard.press(k); await pg.wait_for_timeout(espera)
        async def foto(nome):
            await pg.wait_for_timeout(400); await pg.screenshot(path=f'{OUT}/{nome}.png')
        async def texto(): return await pg.inner_text('#stage')
        async def video_tocando(seg=1.5, timeout=12000):
            try:
                await pg.wait_for_function(f'document.getElementById("v").currentTime > {seg}', timeout=timeout); return True
            except Exception: return False

        print('1. Primeiro acesso')
        await pg.goto(BASE); await pg.wait_for_timeout(800)
        ok('Vamos conectar sua lista' in await texto(), 'abre a tela de conectar lista')
        ok((await pg.input_value('input[data-bind=server]')) == '', 'campo do servidor começa vazio')
        await foto('01-login')
        await pg.fill('input[data-bind=server]', 'localhost:8099')
        ok((await pg.input_value('input[data-bind=user]')) == '' and await pg.evaluate('document.querySelector(".f.on").dataset.id') == 'user', 'servidor vem preenchido e o foco já começa no Usuário')
        await pg.fill('input[data-bind=user]', 'teste')
        await pg.fill('input[data-bind=pass]', 'errada')
        await pg.click('[data-act=go]'); await pg.wait_for_timeout(1200)
        ok('Usuário ou senha incorretos' in await texto(), 'senha errada mostra aviso claro')
        await foto('02-login-erro')
        await pg.fill('input[data-bind=pass]', '1234')
        await pg.click('[data-act=go]'); await pg.wait_for_timeout(1500)
        t = await texto()
        ok('Como você se chama?' in t, 'login certo abre a criação do primeiro perfil')
        await pg.fill('input[data-bind=name]', 'Jamson')
        await pg.click('[data-act=criar]'); await pg.wait_for_timeout(600)
        t = await texto()
        ok('Quem vai assistir?' in t and 'Jamson' in t and 'Vence em 11 dias' in t, 'tela de perfis com vencimento da lista (11 dias)')
        await foto('03-perfis')

        print('2. TV ao Vivo — modelo Cinema (B)')
        await tecla('Enter'); await pg.wait_for_timeout(2500)
        ok(await video_tocando(), 'canal começa a tocar sozinho')
        t = await texto()
        ok('Esportes' in t and 'Esporte Total' in t, 'mostra categorias e canais')
        await pg.wait_for_timeout(1200)
        await foto('04-tv-ao-vivo-cinema')
        await tecla('ArrowDown', 2)
        t = await texto()
        ok('103 · Canal Esportes 1' in t or 'Canal Esportes 1' in t, 'seta para baixo anda pelos canais')
        await tecla('Enter'); await pg.wait_for_timeout(1500)
        src_ok = await pg.evaluate('!!document.getElementById("v").currentSrc || !!window.Hls')
        ok(await video_tocando(0.5), 'OK troca para o canal escolhido')
        await tecla('Enter'); await pg.wait_for_timeout(500)
        ok(await pg.query_selector('.banner') is not None, 'OK de novo abre a tela cheia com a barra do canal')
        await foto('05-tela-cheia-barra')
        await tecla('ArrowUp'); await pg.wait_for_timeout(600)
        ok('Arena Lutas' in await texto(), 'na tela cheia, seta para cima troca de canal (zapping)')
        await tecla('Digit1'); await tecla('Digit1'); await tecla('Digit5'); await pg.wait_for_timeout(1900)
        ok('Cine Clássicos' in await texto(), 'digitar 115 no controle vai direto ao canal 115 (Cine Clássicos)')
        await tecla('b'); await pg.wait_for_timeout(700)
        ok('Arena Lutas' in await texto(), 'botão azul volta ao último canal')
        await tecla('Enter'); await pg.wait_for_timeout(500)
        await tecla('r'); await pg.wait_for_timeout(300)
        ok('nos favoritos' in await pg.inner_text('#toast'), 'botão vermelho favorita o canal')
        await tecla('y'); await pg.wait_for_timeout(400)
        ok(await pg.query_selector('.sheet') is not None, 'botão amarelo abre a lista de categorias')
        await foto('06-categorias')
        await tecla('ArrowDown'); await tecla('Enter'); await pg.wait_for_timeout(1000)
        ok('Arena Lutas' in await texto(), 'categoria Favoritos mostra o canal favoritado')

        print('3. Menu e Ajustes — trocar de modelo')
        await tecla('ArrowLeft'); await pg.wait_for_timeout(300)
        ok(await pg.query_selector('.menu') is not None, 'seta para a esquerda abre o menu')
        await foto('07-menu')
        await tecla('ArrowDown', 5); await tecla('Enter'); await pg.wait_for_timeout(600)
        ok('Aparência da TV ao Vivo' in await texto(), 'menu abre Ajustes › Aparência')
        await foto('08-ajustes')
        await tecla('ArrowLeft'); await tecla('Enter'); await pg.wait_for_timeout(400)
        ok('Modelo Clássico ativado' in await pg.inner_text('#toast'), 'escolhe o modelo Clássico (A)')
        await tecla('Escape'); await pg.wait_for_timeout(2500)
        ok(await pg.query_selector('.la') is not None, 'TV ao Vivo agora aparece no modelo Clássico')
        await video_tocando(0.5)
        await foto('09-tv-ao-vivo-classico')
        await tecla('ArrowLeft'); await tecla('ArrowDown', 5); await tecla('Enter'); await pg.wait_for_timeout(500)
        await tecla('ArrowRight'); await tecla('ArrowRight'); await tecla('Enter'); await pg.wait_for_timeout(300)
        ok('Lista simples' in await pg.inner_text('#toast'), 'escolhe o modelo Lista simples (C)')
        await tecla('ArrowDown'); await tecla('ArrowDown'); await tecla('ArrowRight', 2); await tecla('Enter')
        await tecla('Escape'); await pg.wait_for_timeout(2500)
        ok(await pg.query_selector('.lc') is not None, 'TV ao Vivo agora aparece na Lista simples')
        ok('t-extra' in await pg.evaluate('document.documentElement.className'), 'texto extra grande aplicado')
        await foto('10-tv-ao-vivo-lista-simples-texto-grande')
        await tecla('ArrowLeft'); await pg.click('.mi:has-text("Ajustes")'); await pg.wait_for_timeout(500)
        await tecla('ArrowLeft'); await tecla('Enter'); await pg.wait_for_timeout(300)
        ok('Cinema' in await pg.inner_text('#toast'), 'volta para o modelo Cinema')
        await pg.click('[data-act=texto][data-v=normal]')
        ok('t-' not in await pg.evaluate('document.documentElement.className'), 'texto volta ao normal')
        await tecla('Escape'); await pg.wait_for_timeout(1500)

        print('4. Filmes')
        await tecla('ArrowLeft'); await pg.click('.mi:has-text("Filmes")'); await pg.wait_for_timeout(1500)
        t = await texto()
        ok('Lançamentos' in t and 'O Último Farol' in t, 'abre Filmes com categorias e capas')
        await foto('11-filmes')
        await tecla('ArrowRight'); await pg.wait_for_timeout(600)
        ok('Sinopse de teste do filme' in await texto(), 'mostra a sinopse do filme selecionado')
        await tecla('Enter'); await pg.wait_for_timeout(1500)
        ok(await video_tocando(3, 15000), 'filme começa a tocar')
        await tecla('ArrowRight'); await pg.wait_for_timeout(500)
        pos = await pg.evaluate('document.getElementById("v").currentTime')
        ok(pos > 12, 'seta para a direita avança 10 s (agora em %.0f s)' % pos)
        await foto('12-player-filme')
        await pg.evaluate('document.getElementById("v").currentTime = 45'); await pg.wait_for_timeout(800)
        await tecla('Escape'); await pg.wait_for_timeout(1200)
        await tecla('ArrowUp'); await tecla('ArrowLeft', 2); await pg.wait_for_timeout(1200)
        t = await texto()
        ok('Continuar' in t and 'Pequenos Gigantes' in t, '“Continuar” guarda o filme que foi assistido')
        await tecla('ArrowDown'); await tecla('Enter'); await pg.wait_for_timeout(600)
        t = await texto()
        ok('Continuar de' in t, 'ao reabrir pergunta se quer continuar de onde parou')
        await foto('13-continuar-de-onde-parou')
        await tecla('Escape'); await tecla('Escape'); await pg.wait_for_timeout(1500)

        print('5. Séries')
        await tecla('ArrowLeft'); await pg.click('.mi:has-text("Séries")'); await pg.wait_for_timeout(1500)
        ok('Rota Norte' in await texto(), 'abre Séries')
        await tecla('Enter'); await pg.wait_for_timeout(1200)
        t = await texto()
        ok('Temporada 1' in t and 'A Ponte' in t, 'abre a série com temporadas e episódios')
        await foto('14-serie')
        await tecla('Enter'); await pg.wait_for_timeout(1500)
        ok(await video_tocando(2, 15000), 'episódio começa a tocar')
        ok('T1 · E1' in await texto(), 'player mostra temporada e episódio')
        await pg.evaluate('(()=>{const v=document.getElementById("v"); v.currentTime=v.duration-1;})()')
        await pg.wait_for_timeout(3000)
        ok('PRÓXIMO EM' in await texto(), 'no fim do episódio aparece “próximo em 10 s”')
        await foto('15-proximo-episodio')
        await tecla('Enter'); await pg.wait_for_timeout(1500)
        ok('T1 · E2' in await texto(), 'OK pula para o próximo episódio')
        await tecla('Escape'); await pg.wait_for_timeout(800)
        ok('Continuar T1 · E2' in await texto(), 'série mostra “Continuar T1 · E2”')
        await tecla('Escape'); await pg.wait_for_timeout(600)

        print('6. Busca')
        await tecla('g'); await pg.wait_for_timeout(300)
        await pg.fill('input[data-bind=q]', 'cidade'); await pg.wait_for_timeout(1200)
        ok('Cidade Alta' in await texto(), 'busca encontra a série digitada')
        await foto('16-busca')
        await tecla('Escape'); await tecla('Escape'); await pg.wait_for_timeout(1500)

        print('7. Perfil infantil')
        await tecla('ArrowLeft'); await pg.click('.mi:has-text("Trocar perfil")'); await pg.wait_for_timeout(600)
        await pg.click('[data-act=novo]'); await pg.fill('input[data-bind=name]', 'Kids')
        await pg.click('[data-act=kids]'); await pg.click('[data-act=criar]'); await pg.wait_for_timeout(400)
        await pg.click('.perfil:has-text("Kids")'); await pg.wait_for_timeout(2500)
        t = await texto()
        ok('Kids Mundo' in t and 'Esporte Total' not in t, 'perfil infantil só mostra canais infantis')
        await foto('17-perfil-infantil')

        print('8. Abrir o app de novo (dados guardados)')
        await pg.reload(); await pg.wait_for_timeout(1500)
        ok('Quem vai assistir?' in await texto(), 'reabrindo, lembra a lista e pergunta o perfil')

        print('9. Lista M3U')
        ctx2 = await b.new_context(viewport={'width': 1280, 'height': 720})
        p2 = await ctx2.new_page(); p2.on('pageerror', lambda e: erros.append('JS(m3u): ' + str(e)))
        await p2.goto(BASE); await p2.wait_for_timeout(600)
        await p2.click('[data-act=tab][data-v=m]')
        await p2.fill('input[data-bind=url]', 'http://localhost:8099/lista.m3u')
        await p2.click('[data-act=go]'); await p2.wait_for_timeout(1200)
        await p2.fill('input[data-bind=name]', 'Teste'); await p2.click('[data-act=criar]'); await p2.wait_for_timeout(300)
        await p2.keyboard.press('Enter'); await p2.wait_for_timeout(2500)
        ok('Esporte Total' in await p2.inner_text('#stage'), 'lista M3U funciona (e tela 1280×720 escala certo)')
        await p2.screenshot(path=f'{OUT}/18-m3u-720p.png')
        await b.close()

    print('\nResumo: %d testes OK, %d falhas, %d erros de JavaScript' % (len(oks), len(falhas), len(erros)))
    for e in erros[:20]: print('  ' + e)
    for f in falhas: print('  FALHOU: ' + f)
    sys.exit(1 if falhas or erros else 0)

asyncio.run(main())
