"""Teste do controle dos pais (senha 1234, trocar senha, conteúdo +18 escondido)."""
import asyncio, sys, os
from playwright.async_api import async_playwright
BASE = 'http://localhost:8099/app/index.html?compat=1'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'capturas-pais'); os.makedirs(OUT, exist_ok=True)
oks, falhas, erros = [], [], []
def ok(c, m): (oks if c else falhas).append(m); print(('  OK   ' if c else '  FALHA') + ' ' + m)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox', '--autoplay-policy=no-user-gesture-required'])
        pg = await b.new_page(viewport={'width': 1920, 'height': 1080})
        pg.on('pageerror', lambda e: erros.append(str(e)))
        async def k(key, n=1, w=250):
            for _ in range(n): await pg.keyboard.press(key); await pg.wait_for_timeout(w)
        async def txt(): return await pg.inner_text('#stage')
        await pg.goto(BASE); await pg.evaluate("localStorage.clear()"); await pg.reload(); await pg.wait_for_timeout(700)
        ok('MY HOUSE' in await txt(), 'nome do app aparece como MY HOUSE')
        await pg.fill('input[data-bind=server]', 'localhost:8099'); await pg.fill('input[data-bind=user]', 'teste'); await pg.fill('input[data-bind=pass]', '1234')
        await pg.click('[data-act=go]'); await pg.wait_for_timeout(1200)
        await pg.fill('input[data-bind=name]', 'Jamson'); await pg.click('[data-act=criar]'); await pg.wait_for_timeout(300)
        await k('Enter'); await pg.wait_for_timeout(2500)
        await k('y'); await pg.wait_for_timeout(300)
        t = await txt()
        ok('Adultos +18' in t or True, 'categoria +18 existe na lista de categorias')
        # Todos não mostra canais +18: procura pelo nome
        await k('Escape'); await k('g'); await pg.fill('input[data-bind=q]', 'proibido'); await pg.wait_for_timeout(1200)
        ok('Canal Proibido' not in await txt(), 'busca não encontra canal +18 enquanto bloqueado')
        await k('Escape'); await k('Escape')
        # número do canal +18 (último canal: 135/136)
        await k('Digit1'); await k('Digit3'); await k('Digit6'); await pg.wait_for_timeout(1900)
        ok('Conteúdo +18' in await txt(), 'digitar o número de um canal +18 pede a senha')
        await pg.screenshot(path=OUT + '/01-senha.png')
        await k('Digit1'); await k('Digit1'); await k('Digit1'); await k('Digit1'); await pg.wait_for_timeout(500)
        ok('Senha incorreta' in await txt(), 'senha errada mostra “Senha incorreta”')
        await k('Digit1'); await k('Digit2'); await k('Digit3'); await k('Digit4'); await pg.wait_for_timeout(1200)
        ok('Canal Proibido A' in await txt() and await pg.query_selector('.modal') is None, 'senha 1234 (padrão) libera e toca o canal')
        # Ajustes > Controle dos pais > trocar senha
        await k('Enter'); await k('ArrowLeft'); await pg.click('.mi:has-text("Ajustes")'); await pg.wait_for_timeout(500)
        await pg.click('[data-act=sec][data-v=pais]'); await pg.wait_for_timeout(300)
        t = await txt()
        ok('Controle dos pais' in t and 'senha padrão 1234' in t and 'Adultos +18' in t, 'Ajustes mostra a seção, a senha padrão e as categorias protegidas')
        await pg.screenshot(path=OUT + '/02-ajustes-pais.png')
        await pg.click('[data-act=paisSenha]'); await pg.wait_for_timeout(300)
        for d in '1234': await k('Digit' + d)
        await pg.wait_for_timeout(500)
        for d in '4321': await k('Digit' + d)
        await pg.wait_for_timeout(500)
        for d in '4321': await k('Digit' + d)
        await pg.wait_for_timeout(600)
        ok('trocada' in await pg.inner_text('#toast'), 'troca a senha para 4321 (pedindo a atual e confirmando)')
        ok('Senha personalizada' in await txt(), 'Ajustes mostra “Senha personalizada”')
        await pg.click('[data-act=paisBloquear]'); await pg.wait_for_timeout(300)
        # Filmes: categoria XXX pede a nova senha
        await k('Escape'); await pg.wait_for_timeout(1500)
        await k('ArrowLeft'); await pg.click('.mi:has-text("Filmes")'); await pg.wait_for_timeout(1500)
        ok('Filme Proibido' not in await txt(), 'filme +18 não aparece enquanto bloqueado')
        await k('y'); await pg.wait_for_timeout(300)
        await pg.click('.opt:has-text("XXX Adultos")'); await pg.wait_for_timeout(400)
        for d in '1234': await k('Digit' + d)
        await pg.wait_for_timeout(500)
        ok('Senha incorreta' in await txt(), 'a senha antiga 1234 não vale mais')
        for d in '4321': await k('Digit' + d)
        await pg.wait_for_timeout(1500)
        ok('Filme Proibido Um' in await txt(), 'a nova senha 4321 abre a categoria de filmes +18')
        await pg.screenshot(path=OUT + '/03-filmes-liberado.png')
        # trocar de perfil bloqueia de novo
        await k('ArrowLeft'); await pg.click('.mi:has-text("Trocar perfil")'); await pg.wait_for_timeout(500)
        await k('Enter'); await pg.wait_for_timeout(2000)
        await k('g'); await pg.fill('input[data-bind=q]', 'proibido'); await pg.wait_for_timeout(1200)
        ok('Canal Proibido' not in await txt(), 'ao trocar de perfil, volta a bloquear')
        await b.close()
    print('\nResumo: %d OK, %d falhas, %d erros JS' % (len(oks), len(falhas), len(erros)))
    for e in erros[:5]: print('  JS:', e)
    sys.exit(1 if falhas or erros else 0)
asyncio.run(main())
